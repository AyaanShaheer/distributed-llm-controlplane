// ============================================================================
// ES1: Server-Generated ID
// ============================================================================

func TestES1_CreateWithAutoGeneratedID(t *testing.T) {
	store := NewExperimentStore()
	spec := storeTestSpec()
	spec.ExperimentID = "" // Force auto-generation.

	exp, err := store.Create(spec)
	if err != nil {
		t.Fatalf("unexpected error: %v", err)
	}
	if exp.ID == "" {
		t.Fatal("auto-generated ID should not be empty")
	}
	if !strings.HasPrefix(exp.ID, "exp-") {
		t.Errorf("auto-generated ID should start with 'exp-', got %q", exp.ID)
	}
	if exp.GetState() != StatePending {
		t.Errorf("initial state = %s, want PENDING", exp.GetState())
	}
}

